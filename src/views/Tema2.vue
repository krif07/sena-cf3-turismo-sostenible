      p En conjunto, estos elementos permiten que la narración oral, ya sea tradicional o contemporánea, haga sentir, imaginar y reflexionar, fortaleciendo el vínculo entre el ser humano, la comunidad y la naturaleza.
      p Todo comienza con la historia o fábula, que constituye el conjunto de hechos que se narran, es decir, aquello que realmente sucede dentro del relato. Estos sucesos se organizan en la trama, la cual otorga coherencia y sentido al orden de los acontecimientos, manteniendo el interés del oyente.
      p El espacio es el entorno donde se desarrollan los hechos narrados y contribuye a crear la atmósfera del relato. Puede ser realista, cuando representa lugares posibles y cotidianos, o fantástico, cuando construye escenarios imaginarios o simbólicos. Este elemento influye en el sentido cultural, emocional y simbólico que adquiere la historia.
      p Los personajes son el alma de la narración: el protagonista vive el conflicto principal, el antagonista representa la oposición o desafío, y los personajes secundarios enriquecen la historia con matices, emociones y detalles que la vuelven más verosímil y significativa.
      p El tiempo también cumple un papel fundamental: puede ser mítico, si se sitúa en un pasado lejano o legendario; determinado, cuando ocurre en una época o fecha concreta; o indeterminado, cuando no se precisa el momento, dejando espacio a la imaginación.
      p El narrador es la voz que cuenta los acontecimientos de la historia y define desde qué perspectiva se presentan. Puede ser interno, cuando participa como protagonista, personaje secundario o testigo, o externo, cuando narra desde fuera con conocimiento total o parcial de los hechos. Su posición determina la cercanía con los personajes y el grado de información que recibe el lector u oyente.
      p Finalmente, el conflicto constituye el motor del relato, la tensión que impulsa a los personajes a actuar, mientras que el tema representa la idea central o reflexión que el narrador desea compartir. En conjunto, todos estos elementos narrativos hacen que una narración ficcional no solo relate hechos, sino que emocione, inspire e invite a reflexionar.


